#Student Grade System

marks = int(input("Enter marks: "))

if marks >= 90:
    print("Grade A")
elif marks >= 75:
    print("Grade B")
elif marks >= 65:
    print("Grade c")
elif marks >= 55:
    print("Grade D")
else:
    print("fail")

